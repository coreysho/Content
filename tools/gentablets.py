CONST_MARK = '// ---- the lecterns (poh_tablets.rs2) ----'

def emit_constant(spec, path='scripts/skill_construction/configs/construction.constant'):
    """Appended AFTER the block tools/genfurn.py rewrites, so the two generators never touch
    the same lines. Replaced in place on a re-run."""
    src = read(path).split('\n')
    block = [CONST_MARK,
             '// GENERATED by tools/gentablets.py from tools/tabletspec.json.',
             '//',
             '// How many tablets there are, and how many a lectern can list. The second number is also the',
             '// stride of ~poh_tab_nth\'s switch key and the row count of poh_tabletmenu - the biggest OSRS',
             '// lectern lists exactly eight, so today no lectern needs the second page the window can show.',
             '^poh_tab_items = %d' % len(spec['tablets']),
             '^poh_tab_max = %d' % MAX,
             '',
             '// How many tablets one Study can make before the window closes and you click again. An',
             '// inventory\'s worth: the bound exists because a menu loop that cannot end hangs the script,',
             '// not because there is any reason to stop you.',
             '^poh_tab_loops = 28',
             '',
             '// The cap on Make X (the window\'s quantity buttons, tools/genmenus.py). An inventory\'s',
             '// worth: a tablet costs a soft clay and clay does not stack, so more than this cannot be',
             '// carried to the lectern in the first place. The buttons themselves - 1, 5, 10 - are in',
             '// tools/tabletspec.json, written into the window rather than into constants.',
             '^poh_tab_qty_max = %d' % spec['quantities']['max'],
             '']
    if CONST_MARK in src:
        i = src.index(CONST_MARK)
        j = i + 1
        while j < len(src) and not src[j].startswith('// ---- '):
            j += 1
        src[i:j] = block
    else:
        while src and not src[-1].strip():
            src.pop()
        src += ['', ''] + block
    write(path, src, like=path)

# --------------------------------------------------------------------------- the house spell row

def emit_house_spell(spec):
    """A magic_spell_table row for Teleport to house, and its id. Both append-only: if the row
    or the constant is already there the file is left exactly as it is."""
    h = spec['house_spell']
    cid = 'scripts/skill_combat/configs/magic/spells.constant'
    src = read(cid).split(NL)
    if not any(l.startswith('^teleport_to_house ') for l in src):
        while src and not src[-1].strip():
            src.pop()
        src += ['',
                '// Teleport to house (Corey, 2026-09-11). No button and no spellbook entry - the spell was',
                '// added to the game with Construction, after 377 - but its tablet needs a recipe, and every',
                '// other tablet reads its recipe out of magic_spell_table. So the row exists and only',
                '// poh_tablets.rs2 asks for this id.',
                '^teleport_to_house = %d' % h['id']]
        write(cid, src, like=cid)

    dp = 'scripts/skill_magic/configs/magic_spells.dbrow'
    src = read(dp).split(NL)
    if any(l.strip() == '[magic_spell_teleport_to_house]' for l in src):
        return
    runes = [x for pair in h['runes'] for x in (pair[0], str(pair[1]))]
    runes += ['null', 'null'] * (3 - len(h['runes']))
    while src and not src[-1].strip():
        src.pop()
    src += ['',
            "// Teleport to House. See tools/tabletspec.json: nothing casts this - there is no button for it",
            "// at 377 - the row is here so the house tablet's recipe lives with every other tablet's, and is",
            "// reached only by ~get_spell_data(^teleport_to_house) in poh_tablets.rs2.",
            '[magic_spell_teleport_to_house]',
            'table=magic_spell_table',
            'data=spell,^teleport_to_house',
            'data=members,true',
            'data=name,"Teleport to House"',
            'data=levelrequired,%d' % h['levelrequired'],
            'data=runesrequired,%s' % ','.join(runes),
            'data=experience,%d' % h['experience']]
    write(dp, src, like=dp)



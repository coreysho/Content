#!/usr/bin/env python3
"""Generate the magic-tablet layer: the objs, their pack ids, the lookup tables and the
scripts that make and break them.

WHY GENERATED. Fourteen tablets times five places each one has to be mentioned - the obj
config, obj.pack, the name/level/needs tables the lectern window reads, the break trigger
and the lectern lists - is seventy entries that all have to agree. One table writes them.

WHERE THE NUMBERS COME FROM. Not from here. A tablet's Magic level, its runes and the
experience making it pays are read out of magic_spell_table at generate time, the same row
the spell itself is cast from, and the battery reads them back. So the Varrock tablet cannot
cost something a Varrock teleport does not, and if the spell row is ever retuned the tablet
follows it on the next run.

WHAT THE WIKI SAYS AND WHAT THIS DOES
  - making a tablet needs the spell's Magic level, its runes, and a soft clay, and pays the
    spell's own experience (35 for a Varrock tablet, which is what the spell pays too)
  - a staff does NOT substitute for a rune at a lectern - you are not casting - so this
    reads runesrequired straight off the row rather than through ~staff_runes
  - breaking a tablet needs NO Magic level and gives NO experience
  - the quest gates stay: an Ardougne tablet still wants Plague City, a Watchtower one still
    wants Watch Tower. Those are on USE, which is where the wiki puts them; making is free.
"""

import os, re, json, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, 'tools/tabletspec.json')
NL = chr(10)
MAX = 8                # rows in poh_tabletmenu, and the stride of ~poh_tab_nth's switch key
NEED_PX = 200          # the needs column in poh_tabletmenu, p11_full
NAME_PX = 126          # the name column, p12_full

def read(p, newline=''):
    return open(os.path.join(ROOT, p), newline=newline).read().replace('\r\n', '\n')

def crlf(p):
    raw = open(os.path.join(ROOT, p), 'rb').read()
    return raw.count(b'\r\n') > raw.count(b'\n') / 2

def write(p, lines, like='scripts/skill_construction/scripts/poh_build.rs2'):
    nl = '\r\n' if crlf(like) else '\n'
    body = nl.join(lines).rstrip('\r\n') + nl
    open(os.path.join(ROOT, p), 'wb').write(body.encode('utf-8'))

def q(s):
    return '"%s"' % s.replace('"', "'")

# --------------------------------------------------------------------------- the spell rows

def spell_ids():
    out = {}
    for m in re.finditer(r'^\^(\w+)\s*=\s*(\d+)\s*$',
                         read('scripts/skill_combat/configs/magic/spells.constant'), re.M):
        out[m.group(1)] = int(m.group(2))
    return out

def spell_rows():
    """{spell constant name: {level, runes[(obj,n)], xp, tele, members}} out of the dbrow file."""
    out = {}
    for b in read('scripts/skill_magic/configs/magic_spells.dbrow').split('\n['):
        m = re.search(r'data=spell,\^(\w+)', b)
        if not m:
            continue
        d = {}
        for l in b.split('\n'):
            if l.startswith('data='):
                k, v = l[5:].split(',', 1)
                d.setdefault(k, []).append(v)
        runes = []
        if 'runesrequired' in d:
            p = d['runesrequired'][0].split(',')
            for i in range(0, len(p) - 1, 2):
                if p[i] != 'null':
                    runes.append((p[i], int(p[i + 1])))
        out[m.group(1)] = dict(level=int(d['levelrequired'][0]), runes=runes,
                               xp=int(d.get('experience', ['0'])[0]),
                               tele=(d.get('tele_coord') or [None])[0],
                               members=(d.get('members') or ['false'])[0] == 'true')
    return out

def obj_costs():
    out = {}
    for b in read('scripts/_unpack/377/all.obj').split('\n['):
        n = b.split(']')[0]
        m = re.search(r'^cost=(\d+)', b, re.M)
        if m:
            out[n] = int(m.group(1))
    return out

